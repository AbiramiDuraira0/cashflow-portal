    debt_id,
    debt_type,
    loan_name,
    bank_or_person,
    principal_amount,
    outstanding_amount,
    status,
    created_at
FROM public.debts
WHERE is_delete = false
ORDER BY status ASC, created_at DESC;

-- Summary by status
SELECT 
    status,
    COUNT(*) as count,
    SUM(principal_amount) as total_principal,
    SUM(outstanding_amount) as total_outstanding,
    SUM(amount_paid) as total_paid
FROM public.debts
WHERE is_delete = false
GROUP BY status
ORDER BY status;

-- Summary by type
