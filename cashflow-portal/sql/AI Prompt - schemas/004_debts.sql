-- Description:
-- This table manages both debts (money owed by user) and receivables (money owed to user)
-- Supports tracking of loan details, EMI, status, and payment history

-- ============================================
-- DEBTS TABLE
-- ============================================

CREATE TABLE IF NOT EXISTS public.debts (
    -- Primary Key: Auto-incrementing integer
    debt_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Debt Type: 'debt' (I owe) or 'receivable' (they owe me)
    debt_type         VARCHAR(20) NOT NULL CHECK (debt_type IN ('debt', 'receivable')),

    -- Loan/Debt Details
    loan_name         VARCHAR(100) NOT NULL,
    bank_or_person    VARCHAR(100) NOT NULL,  -- Bank name or person name
    principal_amount  DECIMAL(12, 2) NOT NULL CHECK (principal_amount >= 0),
    interest_rate     DECIMAL(5, 2),  -- Optional interest rate (percentage)
    
    -- EMI Details
    emi_amount        DECIMAL(12, 2) CHECK (emi_amount >= 0),
    emi_start_date    DATE,
    emi_end_date      DATE,
    
    -- Current Status
    outstanding_amount DECIMAL(12, 2) NOT NULL CHECK (outstanding_amount >= 0),
    amount_paid       DECIMAL(12, 2) NOT NULL DEFAULT 0 CHECK (amount_paid >= 0),
    
    -- Status: 'open' or 'closed'
    status            VARCHAR(20) NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
    
    -- Additional Info
    notes             TEXT,
    
    -- Soft Delete Flag
    is_delete         BOOLEAN NOT NULL DEFAULT FALSE,
    
    -- Audit Timestamps
    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ============================================
-- INDEXES
-- ============================================

CREATE INDEX IF NOT EXISTS idx_debts_type ON public.debts (debt_type);
CREATE INDEX IF NOT EXISTS idx_debts_status ON public.debts (status);
CREATE INDEX IF NOT EXISTS idx_debts_is_delete ON public.debts (is_delete);
CREATE INDEX IF NOT EXISTS idx_debts_bank_person ON public.debts (bank_or_person);

-- ============================================
-- TRIGGER FOR AUTO-UPDATE TIMESTAMP
-- ============================================

-- Create trigger function if not exists (reuse from expense table)
CREATE OR REPLACE FUNCTION public.set_debts_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Create trigger
DROP TRIGGER IF EXISTS trg_debts_updated_at ON public.debts;
CREATE TRIGGER trg_debts_updated_at
    BEFORE UPDATE ON public.debts
    FOR EACH ROW
    EXECUTE FUNCTION public.set_debts_updated_at();

