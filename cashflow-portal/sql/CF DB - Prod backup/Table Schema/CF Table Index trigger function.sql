CREATE TABLE public.category (
	category_id int4 NOT NULL GENERATED BY DEFAULT AS IDENTITY,
	category_name varchar(50) NOT NULL,
	is_active bool NOT NULL DEFAULT true,
	created_at timestamptz NOT NULL DEFAULT now(),
	updated_at timestamptz NOT NULL DEFAULT now(),
	sub_category varchar(50) NULL,
	category_icon varchar(10) NULL,
	subcategory_icon varchar(10) NULL,
	notes text NULL,
	CONSTRAINT category_pkey PRIMARY KEY (category_id)
);
CREATE INDEX idx_category_name ON public.category USING btree (category_name);
CREATE INDEX idx_sub_category ON public.category USING btree (sub_category);
CREATE INDEX ix_category_subcategory ON public.category USING btree (sub_category) WHERE (sub_category IS NOT NULL);
CREATE UNIQUE INDEX ux_category_name_subcategory_ci ON public.category USING btree (lower((category_name)::text), lower((COALESCE(sub_category, ''::character varying))::text));

-- Table Triggers

create trigger trg_category_updated_at before
update
    on
    public.category for each row execute function dbo.set_category_updated_at();
	
